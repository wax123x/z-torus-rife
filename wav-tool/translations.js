let currentLang = localStorage.getItem('wav_tool_lang') || navigator.language.slice(0, 2);
if (!translations[currentLang]) {
    currentLang = 'en'; // default to english if lang is not supported
}

function t(key) {
    return translations[currentLang][key] || translations['en'][key] || key;
}

function updateTexts() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
            el.setAttribute('placeholder', t(key));
        } else {
            el.innerHTML = t(key);
        }
    });
    
    // Update JS dynamic texts if they are currently visible
    const resultsDiv = document.getElementById('results');
    if(resultsDiv) {
       if(resultsDiv.innerHTML.includes('Arama yapmak') || resultsDiv.innerHTML.includes('Type something') || resultsDiv.innerHTML.includes('Geben Sie') || resultsDiv.innerHTML.includes('Введите') || resultsDiv.innerHTML.includes('اكتب')) {
           resultsDiv.innerHTML = '<div style="color:#aaa; text-align:center;" data-i18n="type_search">' + t('type_search') + '</div>';
       } else if(resultsDiv.innerHTML.includes('Sonuç bulunamadı') || resultsDiv.innerHTML.includes('No results')) {
           resultsDiv.innerHTML = '<div style="color:#ff6b6b; text-align:center;" data-i18n="no_results">' + t('no_results') + '</div>';
       } else {
           document.querySelectorAll('.use-btn').forEach(btn => {
               btn.innerText = t('btn_use');
           });
       }
    }
}

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('wav_tool_lang', lang);
    updateTexts();
    
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    
    const langSelect = document.getElementById('langSelectWav');
    if(langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    updateTexts();
    changeLanguage(currentLang);
});
